def path_of(cfg):
    return C.A_DIR / (cfg.replace("|", "__").replace("+", "-") + ".npz")


def rows(which, group, items, rule="med3", line="q99", device=True):
    out = [R.HEADER]
    if device:
        for part, label in DEVICE_PARTS:
            out.append(R.fmt_row(label, R.summarise(*R.device_stats(C.RESULTS / "device_A.npz", which, part)), group))
    for cfg, label in items:
        p = path_of(cfg)
        if p.exists():
            out.append(R.fmt_row(f"{label} `{cfg}`", R.summarise(*R.alt_stats(p, which, rule, line)), group))
    return "\n".join(out)


def main():
    md = ["# Protocol A tables (generated by make_tables.py)\n",
          "Columns: false alarms = held-out normal clips with any alarm in their 5 s; caught = fault clips with an alarm "
          "within their 5 s, at the line set from learning data only; AUROC on the clip statistic; best@x = share caught "
          "with the best single threshold (all conditions pooled, in units of each condition's line) that lets at most "
          "x of the held-out normal clips alarm. Alternatives: line = 99th percentile of out-of-sample learning scores "
          "(5 time blocks) after the median-of-3 rule, alarm on the median of the last 3 seconds.\n"]
    for group in ("all", "clean", "noise"):
        md.append(f"\n## Selection set (heavy + light), {group}: models\n")
        md.append(rows("select", group, MAIN))
        md.append(f"\n## Selection set (heavy + light), {group}: sensors\n")
        md.append(rows("select", group, SENSORS, device=False))
    md.append("\n## Selection set, alternatives with the strictest line (highest out-of-sample score, any one second)\n")
    md.append(rows("select", "all", MAIN, rule="any", line="max", device=False))
    for group in ("all", "clean", "noise"):
        md.append(f"\n## CONFIRMATION set (med load), {group}\n")
        md.append(rows("confirm", group, [("g1+ga|fused_pca95_t2_max", "FINAL"),
                                         ("g16+ga|fused_pca95_t2_max", "hardware what-if")]))
    (C.RESULTS / "tables.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
